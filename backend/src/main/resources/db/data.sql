-- ---------------------------------------------------------------------------
-- 7. t_demand　求购需求（对应 REQ-04）
-- 注意：`region` / `valid_until` / `contact` 三个字段在 `DemandPublishDTO` 里是
--       @NotBlank / @NotNull 必填，DDL 也已收紧为 NOT NULL（见
--       migrations/2026-09-23_01_demand_not_null.sql），因此这里必须逐行给值。
--       `valid_until` 用 `DATE_ADD(NOW(), INTERVAL 89 DAY)` 而不是硬编码日期：
--       硬编码的日期总有一天会变成"过去时间"，那批需求就会从列表里静默消失
--       —— 正是这次要修的那类问题。
--       ⚠️ 但相对时间只是把跑道拉长，**不是"永久有效"**：它在导入那一刻就固化成
--          固定的时间戳，满 89 天后求购大厅会再次变空。取 89（而非 90）是给
--          "导入时刻"与"约束判定时刻"之间留一天余量。详见本文件顶部的到期提醒
